export function normalizeLanguage(value) {
  return value === "vi" ? "vi" : DEFAULT_LANGUAGE;
}

export function readLanguage(storage) {
  try { return normalizeLanguage(storage.getItem(LANGUAGE_KEY)); }
  catch { return DEFAULT_LANGUAGE; }
}

export function translate(text, language = DEFAULT_LANGUAGE, values = {}) {
  if (text == null) return "";
  const template = language === "vi" ? text : english[text] ?? text;
  return template.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
}

export class LocalizedError extends Error {
  constructor(key, values = {}) {
    super(translate(key, DEFAULT_LANGUAGE, values));
    this.key = key;
    this.values = values;
  }
}

export class BackendError extends Error {
  constructor(detail, retryAfter) {
    super(detail + (retryAfter ? " " + translate("Thử lại sau {seconds} giây.", "en", { seconds: retryAfter }) : ""));
    this.detail = detail;
    this.retryAfter = retryAfter;
  }
}

export function errorMessage(error, language = DEFAULT_LANGUAGE) {
  if (error instanceof LocalizedError) return translate(error.key, language, error.values);
  if (error instanceof BackendError) return translate(error.detail, language) + (error.retryAfter
    ? " " + translate("Thử lại sau {seconds} giây.", language, { seconds: error.retryAfter }) : "");
  return translate(error?.message || String(error || ""), language);
}
